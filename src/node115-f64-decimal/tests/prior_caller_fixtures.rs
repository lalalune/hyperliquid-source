//! Exact successful caller observations retained in l1-shared-f64-to-decimal-115/caller_cases.tsv.
use node115_f64_decimal::from_f64_bits;

#[test]
fn retained_caller_words_match() {
    let cases: &[(u64, [u32; 4])] = &[
        (
            0x0000000000000000,
            [0x00000000, 0x00000000, 0x00000000, 0x00000000],
        ),
        (
            0x8000000000000000,
            [0x80000000, 0x00000000, 0x00000000, 0x00000000],
        ),
        (
            0x0000000000000001,
            [0x00000000, 0x00000000, 0x00000000, 0x00000000],
        ),
        (
            0x000fffffffffffff,
            [0x00000000, 0x00000000, 0x00000000, 0x00000000],
        ),
        (
            0x0010000000000000,
            [0x00000000, 0x00000000, 0x00000000, 0x00000000],
        ),
        (
            0x3ff0000000000000,
            [0x00000000, 0x00000000, 0x00000001, 0x00000000],
        ),
        (
            0xbff0000000000000,
            [0x80000000, 0x00000000, 0x00000001, 0x00000000],
        ),
        (
            0x3fb999999999999a,
            [0x00010000, 0x00000000, 0x00000001, 0x00000000],
        ),
        (
            0x4024000000000000,
            [0x00000000, 0x00000000, 0x0000000a, 0x00000000],
        ),
    ];
    for &(bits, words) in cases {
        assert_eq!(
            from_f64_bits(bits).unwrap().words(),
            words,
            "bits {bits:016x}"
        );
    }
}
