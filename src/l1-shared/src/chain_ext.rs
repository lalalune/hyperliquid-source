/// Returns `true` iff `addr` is present in the chain's privileged address set.
pub fn is_chain_privileged_address(chain: ChainKind, addr: &Address) -> Result<bool, &'static str> {
    let set = chain_addresses(chain)?;
    Ok(set.binary_search(addr).is_ok())
}
