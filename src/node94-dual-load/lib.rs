#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn relative_slot_uses_addend_and_bias() {
        assert_eq!(
            lookup(0, 4096),
            Registers {
                rax: 2142632 + 4096,
                rdx: 8
            }
        );
    }

    #[test]
    fn neighboring_raw_word_is_not_relocated() {
        assert_eq!(
            lookup(20, u64::MAX),
            Registers {
                rax: 98,
                rdx: 13637704200709732
            }
        );
    }

    #[test]
    fn relative_addition_wraps_without_dereference() {
        assert_eq!(lookup(253, 0_u64.wrapping_sub(2032517)).rax, 0);
    }
}
