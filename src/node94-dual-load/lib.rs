//! Digest-specific numeric loaded-image projection of node94's dual load.

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct Registers {
    pub rax: u64,
    pub rdx: u64,
}

/// Return the observed pair for a copied entry byte and numeric ELF load bias.
///
/// The two complete 256-word reachable windows are reconstructed from pinned
/// ELF data, not inferred logical table lengths. Exactly 127 B-window words
/// receive symbol-zero R_X86_64_RELATIVE bias; other words retain file values.
/// Correspondence requires a successfully mapped image with these data bytes
/// unchanged after relocation, and a valid stable original input-byte read.
/// The function does not dereference returned numbers or execute target code.
pub fn lookup(index: u8, load_bias: u64) -> Registers {
    let i = usize::from(index);
    let relocated = (RELOCATED[i / 64] >> (i % 64)) & 1 != 0;
    let rax = B[i].wrapping_add(if relocated { load_bias } else { 0 });
    Registers { rax, rdx: A[i] }
}

