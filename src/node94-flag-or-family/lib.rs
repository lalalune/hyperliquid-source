//! Full reachable data-window projection of three node94 indexed-OR leaves.

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum Family {
    Entry15625e0,
    Entry1566100,
    Entry1568bb0,
}

/// The RAX/RCX values and numeric destination of the four-byte update.
