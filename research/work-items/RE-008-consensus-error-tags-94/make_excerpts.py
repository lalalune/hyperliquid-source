#!/usr/bin/env python3
"""Regenerate objdump-excerpts.txt for the RE-008 consensus error-tag packet.

Needs GNU objdump on PATH (the excerpts were produced with the version in
RECORDED_VERSION). Reads only the pinned binary and this packet's
consensus-error-tags.json, which supplies the census sites to cite.

  make_excerpts.py            write the excerpts to stdout
  make_excerpts.py --write    replace objdump-excerpts.txt
  make_excerpts.py --check    exit 0 if the committed file is identical,
                              1 if it differs, 2 if objdump is not the
                              recorded GNU version or the binary is wrong
"""
import argparse
import hashlib
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
BIN_REL = "artifacts/node/94/hl-node"
BIN_SHA256 = "3b7179cd967d1b13b683e05debfc685ad4c750e918226402d5d575eff1c0459f"
RECORDED_VERSION = "GNU objdump (GNU Binutils) 2.47.20260726"
OUT = HERE / "objdump-excerpts.txt"
DIS = ["-d", "-M", "intel", "--insn-width=15"]
RULE = "=" * 78


def objdump_version():
    exe = shutil.which("objdump")
    if not exe:
        return None, None
    out = subprocess.run([exe, "--version"], capture_output=True, text=True).stdout
    return exe, (out.splitlines()[0] if out else "")


def run(exe, args):
    out = subprocess.run([exe] + args + [BIN_REL], cwd=ROOT, capture_output=True, text=True,
                         check=True).stdout
    lines = out.splitlines()
    i = next(k for k, ln in enumerate(lines)
             if ln.startswith(("Disassembly of section", "Contents of section")))
    return [ln.rstrip() for ln in lines[i:]]  # objdump -s pads short lines with spaces


def dis(exe, lo, hi):
    return run(exe, DIS + [f"--start-address={lo:#x}", f"--stop-address={hi:#x}"])


def ro(exe, lo, hi):
    return run(exe, ["-s", "-j", ".rodata", f"--start-address={lo:#x}", f"--stop-address={hi:#x}"])


def section(title, notes, cmds, body):
    out = [RULE, title]
    out += [f"    {n}" for n in notes]
    out += [f"    $ {c}" for c in cmds]
    out += [RULE, ""] + body + [""]
    return out


def cmd_dis(lo, hi):
    return f"objdump {' '.join(DIS)} --start-address={lo:#x} --stop-address={hi:#x} {BIN_REL}"


def cmd_ro(lo, hi):
    return f"objdump -s -j .rodata --start-address={lo:#x} --stop-address={hi:#x} {BIN_REL}"


def h(s):
    return int(s, 16)


def generate(exe, version):
    d = json.loads((HERE / "consensus-error-tags.json").read_text())
    out = [
        "RE-008 consensus error-tag table: cited bytes (node #94)",
        f"binary: {BIN_REL}",
        f"sha256: {BIN_SHA256}",
        f"tool:   {version}",
        "coordinate system: linked virtual address; instruction start includes any REX prefix.",
        "generated by: python3 -I -B research/work-items/RE-008-consensus-error-tags-94/make_excerpts.py --write",
        "Every window below is objdump output with trailing spaces stripped (raw instruction bytes",
        "shown; --insn-width=15 keeps each instruction on one line). Section [12] selects single",
        "lines by address.",
        "",
    ]
    heads = [(m["fde"], m["jump_table"], m["dispatch"]["tail"]) for m in d["formatter_monomorphs"]]
    shapes = {"0x4753d60": "serde_json-shaped", "0x44c4480": "core::fmt-shaped", "0x244e3f0": "core::fmt-shaped"}
    for n, (fde, table, tail) in enumerate(heads, 1):
        lo, hi = h(fde), h(tail) + 9
        out += section(f"[{n}] Dispatch head of formatter monomorph {fde} ({shapes[fde]}; jump table {table})",
                       ["word0 load, rcx = 2^63, the pinned select bytes (xor/test/mov eax,0x27/cmovs),",
                        "lea rcx,[rip+table] and the pinned tail (movsxd/add/jmp rax)."],
                       [cmd_dis(lo, hi)], dis(exe, lo, hi))
    x = d["variant_index_crosscheck"]
    lo, hi = h(x["fde"]), h(x["dispatch"]["tail"]) + 9
    out += section(f"[4] Dispatch head of the fourth monomorph {x['fde']} (jump table {x['jump_table']})",
                   ["rcx = 2^63 via movabs r12,0x8000000000000003 then lea rcx,[r12-0x3]; same select",
                    "and tail bytes; word0 is loaded from [rsi]."],
                   [cmd_dis(lo, hi)], dis(exe, lo, hi))
    tables = [m["jump_table"] for m in d["formatter_monomorphs"]] + [x["jump_table"]]
    body, cmds = [], []
    for tb in tables:
        lo, hi = h(tb), h(tb) + 4 * (d["tag_count"] + 1)
        cmds.append(cmd_ro(lo, hi))
        body += ro(exe, lo, hi) + [""]
    out += section("[5] Jump tables: 43 little-endian sdata4 entries each (k = 0x00..0x2a), target = table + entry",
                   [f"tables, in order: {', '.join(tables)}"], cmds, body[:-1])
    out += section("[6] Arms k=0x1c and k=0x1d of copy 0x4753d60 (serde_json-shaped)",
                   ["0x1c (0x4755240): '{' '\"' pushes, lea rsi -> 0x6fbb2d, mov edx,0x14 (len 20), call.",
                    "0x1d (0x4755328): lea rsi -> 0x6fbb41, mov edx,0x12 (len 18), jmp to the writer tail."],
                   [cmd_dis(0x4755240, 0x4755358)], dis(exe, 0x4755240, 0x4755358))
    body = dis(exe, 0x44C4E63, 0x44C4E95) + [""] + dis(exe, 0x244ED73, 0x244EDA5)
    out += section("[7] Arm k=0x1c of copies 0x44c4480 and 0x244e3f0 (core::fmt-shaped)",
                   ["mov r12,[r15+0x18]; lea rsi,name; mov edx,0x14; call r12 (writer through a vtable slot)."],
                   [cmd_dis(0x44C4E63, 0x44C4E95), cmd_dis(0x244ED73, 0x244EDA5)], body)
    out += section("[8] Arm k=0x1c of the fourth monomorph 0x4752890 (explicit index)",
                   ["lea rsi -> 0x6fb968 + mov edx,0x5; lea r8 -> 0x6fbb2d + mov r9d,0x14; mov ecx,0x1c; call."],
                   [cmd_dis(0x4753841, 0x4753874)], dis(exe, 0x4753841, 0x4753874))
    pools = [(0x6FBB10, 0x6FBB80), (0x6F5180, 0x6F51C0), (0x3E3F50, 0x3E3F80), (0x6FB960, 0x6FB990),
             (0x20A280, 0x20A290)]
    body = []
    for lo, hi in pools:
        body += ro(exe, lo, hi) + [""]
    out += section("[9] .rodata name bytes",
                   ["0x6fbb2d / 0x6f518a / 0x3e3f51: 'ClientBlockMissingTx' (20) directly followed by",
                    "'CommitProofChildQc' (18) at +0x14, in the pools of copies 0x4753d60 / 0x44c4480 /",
                    "0x244e3f0. 0x6fb968: 'Error' (5), passed in rsi/edx by the fourth monomorph.",
                    "0x20a280: 'Hardfork' (8), one string whose pointer all three copies share."],
                   [cmd_ro(lo, hi) for lo, hi in pools], body[:-1])
    out += section("[10] FDE 0x47b01b0, whole (census label fde_0x47b01b0; lead label verify_signed_block)",
                   ["0x47b01c9 movabs r13,0x800000000000002a; 0x47b0205 / 0x47b040a / 0x47b043e compare it;",
                    "0x47b0416 lea rax,[r13-0x2a] (= 2^63) compared at 0x47b041a; shared store 0x47b03a1",
                    "mov [rbx],r13 fed by add r13,-0x1e (0x47b039d), -0x26 (0x47b0480), -0x25 (0x47b0489)",
                    "and by the unmodified value (je at 0x47b041e and 0x47b0442)."],
                   [cmd_dis(0x47B01B0, 0x47B0492)], dis(exe, 0x47B01B0, 0x47B0492))
    out += section("[11] FDE 0x47594f0, two windows (census label fde_0x47594f0; lead label verify_tc)",
                   ["0x47595ba movabs r12,0x..2a; 0x47595cd lea rax,[r12-0x2] stored at 0x47595d2 and passed",
                    "by address (lea rdi,[rsp+0x28]) to 0x4b1a270; 0x4759659 movabs rcx,0x..2a; add rcx,-0x2",
                    "stored at 0x4759667; 0x4759673 add r12,-0x1f stored at 0x4759677; 0x475967f movabs",
                    "rax,0x..2a; add rax,-0x1b stored at 0x475968d. Second window: the call through slot",
                    "0x5776ae8 (0x4759865), mov ebp,eax, movabs r12,0x..2a (0x4759875), and test bpl,bpl",
                    "(0x4759936) choosing 0x..2a or add r12,-0x20 (0x..0a) before the store at 0x4759677."],
                   [cmd_dis(0x47595BA, 0x475969D), cmd_dis(0x4759850, 0x4759963)],
                   dis(exe, 0x47595BA, 0x475969D) + [""] + dis(exe, 0x4759850, 0x4759963))
    body, cmds = [], []
    for n, c in enumerate(d["census"], 1):
        lo, hi = h(c["fde"]), h(c["fde_end"])
        roles = {}

        def add(site, role, value):
            roles.setdefault(h(site), {}).setdefault(role, set()).add(value[-2:])

        for s in c["niche_movabs_sites"]:
            add(s["site"], "movabs", s["value"])
        for key in ("in_range_tag_stores", "niche_0x00_stores", "past_table_niche_stores",
                    "out_of_range_niche_stores"):
            for s in c[key]:
                add(s["site"], "store", s["value"])
        for s in c["niche_comparisons"]:
            add(s["site"], "cmp", s["value"])
        lines = {}
        for ln in dis(exe, lo, hi):
            m = re.match(r"^\s*([0-9a-f]+):\t", ln)
            if m:
                lines[int(m.group(1), 16)] = ln
        lead = f"; lead label {c['lead_label']}" if c["lead_label"] else ""
        body.append(f"[12.{n}] FDE {c['fde']}..{c['fde_end']} (census label {c['label']}{lead})")
        for va in sorted(roles):
            tags = "; ".join(f"{r} {' '.join(sorted(v))}" for r, v in sorted(roles[va].items()))
            body.append(f"  {tags:<20}|{lines[va]}")
        body.append("")
        cmds.append(cmd_dis(lo, hi) + "  (lines selected by address)")
    out += section("[12] Census: the instruction at every niche movabs, store and compare site in the JSON",
                   ["Left column: role and niche low byte (value = 0x80000000000000xx), from",
                    "consensus-error-tags.json census[]; right: the objdump line at that address."],
                   cmds, body[:-1])
    return ("\n".join(out).rstrip("\n") + "\n").encode()


def main(argv=None):
    ap = argparse.ArgumentParser(description="Regenerate objdump-excerpts.txt (GNU objdump required).")
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--write", action="store_true")
    g.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    exe, version = objdump_version()
    if not exe or not version.startswith("GNU objdump"):
        print(f"make_excerpts: GNU objdump required (found {version!r})", file=sys.stderr)
        return 2
    if a.check and version != RECORDED_VERSION:
        print(f"make_excerpts: objdump is {version!r}, excerpts were made with {RECORDED_VERSION!r}",
              file=sys.stderr)
        return 2
    if hashlib.sha256((ROOT / BIN_REL).read_bytes()).hexdigest() != BIN_SHA256:
        print("make_excerpts: binary sha256 mismatch", file=sys.stderr)
        return 2
    text = generate(exe, version)
    if a.check:
        if OUT.read_bytes() != text:
            print("make_excerpts: objdump-excerpts.txt differs from regenerated output", file=sys.stderr)
            return 1
        print("make_excerpts: objdump-excerpts.txt regenerates byte for byte")
        return 0
    if a.write:
        OUT.write_bytes(text)
    else:
        sys.stdout.buffer.write(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
