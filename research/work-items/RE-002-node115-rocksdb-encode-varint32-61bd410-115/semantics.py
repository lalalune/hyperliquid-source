#!/usr/bin/env python3
"""Anchor every behavioural claim about encode_varint32 to a target
instruction.

Bounded-claim binding: each row names one claim, the exact virtual address
of the instruction that carries it, and the bytes found there. Every
semantic statement in README.md / records.json has a row here, so a
reviewer can check the claim against the target image itself rather than
against another model.

Regenerated by verify.py and checked byte-for-byte; nothing is executed.
"""
import re
import subprocess
import sys
from pathlib import Path

import capstone

ROOT = Path(__file__).resolve().parents[3]
BINARY = ROOT / "artifacts" / "node" / "115" / "hl-node"
PACKET = (ROOT / "research" / "work-items"
          / "RE-002-node115-rocksdb-encode-varint32-61bd410-115")

START = 0x61BD410
END = 0x61BD4E9

# (claim, virtual address, note)
CLAIMS = [
    ("function entry", 0x61BD410,
     "endbr64: an indirect-branch target, so the window is a routine entry"),
    ("dst becomes the return base", 0x61BD414,
     "mov %rdi,%rax: the return value starts as the buffer pointer"),
    ("1-byte class test", 0x61BD417,
     "cmp $0x7f,%esi with ja: the test is UNSIGNED above, so v == 0x7f stays in this class"),
    ("1-byte class jump", 0x61BD41A,
     "ja 0x61bd430 leaves the 1-byte class only for v > 0x7f"),
    ("1-byte store", 0x61BD41C,
     "mov %sil,(%rdi): the whole value is stored unmasked because v <= 0x7f"),
    ("1-byte end pointer", 0x61BD41F,
     "lea 0x1(%rdi),%rdx: the returned end pointer is dst+1 - the value returned is a POINTER, not a count"),
    ("2-byte continuation bit", 0x61BD435,
     "or $0xffffff80,%r8d sets bit 7 of the first byte, i.e. 'more bytes follow'"),
    ("2-byte shift for the final byte", 0x61BD439,
     "shr $0x7,%ecx: the second byte is v>>7, stored unmasked - safe because the bound is 0x3fff"),
    ("2-byte class bound", 0x61BD43C,
     "cmp $0x3fff,%esi: the second class ends at 0x3fff inclusive"),
    ("2-byte stores", 0x61BD448,
     "mov %r8b,(%rdi) then mov %cl,0x1(%rdi): TWO separate byte stores"),
    ("3-byte class bound", 0x61BD460,
     "cmp $0x1fffff,%esi: the third class ends at 0x1fffff inclusive"),
    ("3-byte stores", 0x61BD4BA,
     "mov %dil,0x2(%rax): a third separate byte store, end pointer dst+3 at 0x61bd4b0"),
    ("4-byte class bound", 0x61BD474,
     "cmp $0xfffffff,%esi: the fourth class ends at 0x0fffffff inclusive"),
    ("4-byte word composition", 0x61BD495,
     "shl $0x8,%edi and the surrounding or/shl build the four bytes in a register"),
    ("4-byte SINGLE 32-bit store", 0x61BD4A0,
     "mov %ecx,(%rax): the 4-byte class writes with ONE unaligned 32-bit store, unlike every other class"),
    ("5-byte continuation on the 4th byte", 0x61BD4C8,
     "or $0xffffff80,%edi sets the continuation bit of the fourth byte only in the 5-byte class"),
    ("5-byte top byte", 0x61BD4CB,
     "shr $0x1c,%esi: the fifth byte is v>>28, so only its low nibble is non-zero for a uint32_t"),
    ("5-byte stores", 0x61BD4E0,
     "mov %sil,0x4(%rax): five separate byte stores, end pointer dst+5"),
    ("a return tail", 0x61BD423,
     "mov %rdx,%rax then ret at 0x61bd426: rdx is dst+n. The 4- and 5-byte classes jmp here (0x61bd4a2, 0x61bd4e4) and the 1-byte class falls into it; the 2- and 3-byte classes have their OWN identical mov/ret pairs at 0x61bd44e and 0x61bd4be, so the routine has three tail sites, not one"),
]


def va_to_off(va):
    out = subprocess.check_output(["readelf", "-lW", str(BINARY)]).decode()
    for line in out.splitlines():
        p = line.split()
        if p and p[0] == "LOAD":
            v, o, f = int(p[2], 16), int(p[1], 16), int(p[4], 16)
            if v <= va < v + f:
                return o + (va - v)
    raise ValueError(hex(va))


def rows():
    md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_64)
    data = BINARY.read_bytes()
    out = []
    for claim, va, note in CLAIMS:
        assert START <= va < END, (claim, hex(va))
        off = va_to_off(va)
        ins = next(iter(md.disasm(data[off:off + 15], va)))
        raw = data[off:off + ins.size]
        out.append({
            "claim": claim,
            "va": hex(va),
            "size": str(ins.size),
            "bytes": raw.hex(),
            "instruction": f"{ins.mnemonic} {ins.op_str}".strip(),
            "note": note,
        })
    return out


def write(path=None):
    path = path or (PACKET / "semantics.tsv")
    rows_ = rows()
    cols = ("claim", "va", "size", "bytes", "instruction", "note")
    with open(path, "w") as fh:
        fh.write("\t".join(cols) + "\n")
        for r in rows_:
            fh.write("\t".join(r[c] for c in cols) + "\n")
    return len(rows_)


def main():
    n = write()
    print(f"wrote semantics.tsv ({n} claim anchors)")
    return 0


if __name__ == "__main__":
    sys.exit(main())