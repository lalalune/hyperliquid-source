#!/usr/bin/env python3
"""Verify the vaults-subaccount-create-94 packet: manifest, regenerated JSON and excerpts, pinned facts."""
import hashlib
import importlib.util
import json
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
BIN_SHA256 = "3b7179cd967d1b13b683e05debfc685ad4c750e918226402d5d575eff1c0459f"
PACKET_JSON_SHA256 = "f0b9e4b9addad4fafaa93e82c5f126b73d81a1b02ad3b4b5d31d70df869d8fe6"
FILES = ("README.md", "objdump-excerpts.txt", "subaccount-create.json", "verify.py")
IGNORED = {"MANIFEST.sha256", "__pycache__"}
FIRST_PARTY = "/home/ubuntu/hl/code_Mainnet/"


class VerifyError(Exception):
    pass


def check(cond, msg):
    if not cond:
        raise VerifyError(msg)


def manifest_problems(here: Path) -> list:
    """Every listed file hashes to its line; the list and the directory are exactly FILES."""
    try:
        lines = (here / "MANIFEST.sha256").read_text().splitlines()
    except OSError as e:
        return [f"cannot read MANIFEST.sha256: {e}"]
    problems, names = [], []
    for i, line in enumerate(lines, 1):
        parts = line.split("  ", 1)
        if len(parts) != 2 or not re.fullmatch(r"[0-9a-f]{64}", parts[0]):
            problems.append(f"MANIFEST line {i} is malformed")
            continue
        digest, name = parts
        names.append(name)
        p = here / name
        if not p.is_file():
            problems.append(f"{name} is missing")
        elif hashlib.sha256(p.read_bytes()).hexdigest() != digest:
            problems.append(f"manifest mismatch for {name}")
    if sorted(names) != sorted(FILES) or len(names) != len(set(names)):
        problems.append(f"MANIFEST lists {sorted(names)}, expected {sorted(FILES)}")
    present = sorted(p.name for p in here.iterdir() if p.name not in IGNORED)
    if present != sorted(FILES):
        problems.append(f"packet directory holds {present}, expected {sorted(FILES)}")
    return problems


def load(root: Path, name: str):
    spec = importlib.util.spec_from_file_location(name, root / f"tools/{name}.py")
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


def excerpt_regeneration_skip_reason(here: Path = HERE):
    """None when GNU objdump of the recorded version is on PATH, else why the bodies are not regenerated."""
    head = (here / "objdump-excerpts.txt").read_text().splitlines()[1]
    if not shutil.which("objdump"):
        return "objdump is not on PATH"
    p = subprocess.run(["objdump", "--version"], capture_output=True, text=True)
    ver = p.stdout.splitlines()[0] if p.returncode == 0 and p.stdout else ""
    if head != f"# tool: {ver}":
        return f"objdump on PATH is {ver!r}; the excerpts record {head[8:]!r}"
    return None


def verify(here: Path = HERE, root: Path = ROOT) -> str:
    """Raise VerifyError on the first problem; return a note on how the excerpt bodies were checked."""
    # 1) Manifest: exact file set, every hash.
    problems = manifest_problems(here)
    check(not problems, "; ".join(problems))

    binary_path = root / "artifacts/node/94/hl-node"
    binary = binary_path.read_bytes()
    check(hashlib.sha256(binary).hexdigest() == BIN_SHA256, "binary sha256")

    # 2) Regenerate the evidence JSON; require the pinned hash and byte equality.
    sac = load(root, "subaccount_create")
    text = sac.render(sac.build(binary))
    check(hashlib.sha256(text).hexdigest() == PACKET_JSON_SHA256, "regenerated subaccount-create.json hash")
    check((here / "subaccount-create.json").read_bytes() == text, "subaccount-create.json differs from tool output")
    d = json.loads(text)

    # 3) Excerpts: this binary, exactly the tool's windows, and (with the recorded GNU objdump) the same bytes.
    ex = (here / "objdump-excerpts.txt").read_text()
    check(f"# binary sha256: {BIN_SHA256}" in ex, "excerpt binary digest")
    windows = [(int(a, 16), int(b, 16)) for a, b in
               re.findall(r"^## .*\[objdump --start-address=(0x[0-9a-f]+) --stop-address=(0x[0-9a-f]+)\]$", ex, re.M)]
    check(windows == [(w[1], w[2]) for w in sac.excerpt_windows()], "excerpt windows differ from the tool's")
    skip = excerpt_regeneration_skip_reason(here)
    if skip is None:
        with tempfile.TemporaryDirectory() as td:
            out = Path(td) / "excerpts.txt"
            sac.write_excerpts(binary_path, out)
            check(out.read_bytes() == (here / "objdump-excerpts.txt").read_bytes(),
                  "objdump-excerpts.txt differs from the regenerated excerpts")
        note = "excerpt bodies regenerated byte for byte"
    else:
        note = f"excerpt bodies not regenerated ({skip}); headers and windows checked"

    # 4) Pinned facts.
    dsp = d["dispatch"]
    check((dsp["exchange_tag"], dsp["index"], dsp["tag_bias"], dsp["arm"], dsp["call_site"], dsp["handler"]) ==
          (122, 6, 116, "0x2759d2a", "0x2759d4d", "0x27e3140"), "dispatch")
    fns = d["functions"]
    for name, (s, e, size) in {"handler": ("0x27e3140", "0x27e3744", 1540), "creator": ("0x36f3610", "0x36f3c15", 1541),
                               "deriver": ("0x36f3c20", "0x36f3ed0", 688), "name_helper": ("0x36f43c0", "0x36f4627", 615),
                               "ethabi_build3": ("0x3c97900", "0x3c97a65", 357),
                               "volume_producer": ("0x275fee0", "0x2760040", 352),
                               "vec_entry": ("0x3596680", "0x35967a8", 296),
                               "volume_report": ("0x358dcd0", "0x358de41", 369)}.items():
        check((fns[name]["start"], fns[name]["end"], fns[name]["size"]) == (s, e, size), f"{name} window")
    s = d["summary"]
    check((s["functions"], s["shapes"], s["pinned_instructions"], s["links"]) == (27, 191, 989, 21), "pinned windows")
    check((s["status_stores"], s["status_stores_imm16"], s["status_stores_register"]) == (12, 7, 5), "status stores")
    check((s["status_rows"], s["status_rows_imm16"], s["status_rows_register"], s["control_rows"]) == (8, 6, 2, 5),
          "status rows")
    order = [(r["seq"], r["owner"], r["status"]) for r in d["check_order"]]
    check(order == [(1, "handler", None), (2, "handler", 0xD8), (3, "handler", None), (4, "creator", 0xDD),
                    (5, "creator", 0xD6), (6, "creator", None), (7, "creator", 0xD8), (8, "creator", 0x143),
                    (9, "name_helper", 0xD9), (10, "name_helper", 0xD7), (11, "creator", None),
                    (12, "creator", 0x186), (13, "handler", None)], "check order")
    loads = {r["seq"]: (r["status_load"]["load_va"], r["fail_to_store_straight_line"])
             for r in d["check_order"] if "status_load" in r}
    check(loads == {1: ("0x27e3183", True), 6: ("0x36f3775", True), 13: ("0x27e33c0", True)}, "propagated statuses")
    check(d["calls"]["summary"] == {"calls": 44, "direct": 16, "register": 3, "through_slot": 25,
                                    "through_slot_distinct_slots": 13, "through_slot_relative": 11,
                                    "through_slot_glob_dat": 2}, "call sites")
    cs = d["call_slots"]["summary"]
    check((cs["references"], cs["distinct_slots_used_by_five_windows"], cs["resolved"], cs["relative"],
           cs["glob_dat"]) == (35, 17, 17, 15, 2), "call slots")
    slots = {x["slot"]: x for x in d["call_slots"]["slots"]}
    check(slots["0x5774f40"].get("target") == "0x36f3c20" and slots["0x5774f48"].get("target") == "0x36f3610" and
          slots["0x576e378"].get("symbol") == "bcmp" and slots["0x576e050"].get("target") == "0x1344900" and
          slots["0x5773190"].get("target") == "0x358dcd0", "slot targets")
    locs = {x["label"]: x for x in d["locations"]}
    check((locs["insert_assert"]["file"], locs["insert_assert"]["line"], locs["insert_assert"]["col"]) ==
          (FIRST_PARTY + "l1/src/sub_account.rs", 69, 13), "insert assert Location")
    check(locs["scaled_vlm_15_21"]["file"] == FIRST_PARTY + "l1/src/scaled_vlm.rs" and
          locs["raw_vlm_17_21"]["file"] == FIRST_PARTY + "l1/src/raw_vlm.rs", "volume step Locations")
    msgs = {a["status"]: a.get("text", a.get("rendered")) for a in d["status_formatter"]["arms"]}
    check(msgs == {0xD6: "Too many sub-accounts.", 0xD7: "Sub-account name already taken.",
                   0xD8: "Duplicate sub-account user {}",
                   0xD9: "Sub-account name must be between 1 and 16 characters long.",
                   0xDD: "Cannot create sub-accounts until enough volume traded. Required: ${}. Traded: ${}.",
                   0x143: "Invalid input length",
                   0x57: "Too many extra agents for cumulative volume traded. Current limit is {}"}, "status messages")
    check([t["variant"] for t in d["token_debug"]["builder_tokens"]] == ["String", "Address", "Uint"], "token tags")
    ww = d["word_writer"]
    check([a["tag"] for a in ww["arms"] if a["arm"] == ww["int_uint_arm"]] == [3, 4] and
          [(w["word_offset"], w["token_disp"]) for w in ww["int_uint_word"]] == [(0, 32), (8, 24), (16, 16), (24, 8)],
          "word writer")
    c = d["constants"]
    check((c["min_volume_raw"], c["reciprocal_magic"], c["reciprocal_shift"], c["volume_per_extra_sub_raw"],
           c["cap_quotient_clamp"], c["cap_addend"]) == (0x989680, 0xDBE6FECEBDEDD5BF, 97, 10 ** 10, 40, 10),
          "volume and cap constants")
    check((c["name_len_upper_tier"], c["name_len_accepted_lo"], c["name_len_accepted_hi"]) == (100, 1, 16), "name tiers")
    check((c["keccak_rate"], c["keccak_delimiter"], c["keccak_rounds"], c["digest_len"]) == (136, 1, 24, 32), "keccak")
    check(d["kept_digest"]["slice"] == [0, 20], "kept digest slice")
    check([x["va"] for x in d["callers_e8_rel32"]["volume_producer"]] == ["0x27677d4", "0x27e3317"], "producer callers")
    bs = d["byte_scans"]["windows"]
    check(bs["name_sibling"] == {"imm32_0x989680": [], "imm64_magic": []} and
          bs["other_volume_user"] == {"imm32_0x989680": ["0x27677e5"], "imm64_magic": ["0x2767862"]}, "byte scans")
    rp = d["reciprocal_proof"]
    check(rp["certificate_ok"] and rp["all_boundary_vectors_pass"] and rp["wrong_magic_minus1_failures_of_3"] == 2,
          "reciprocal proof")
    cb = d["cap_boundaries"]
    check((cb["min_cap"], cb["max_cap"]) == (10, 50), "cap min/max")
    dm = d["derivation_model"]
    check(dm["kats_pass"] and dm["sha3_crosscheck_equal"] == len(dm["sha3_crosscheck_lengths"]) == 11 and
          dm["uint_word_checked_against_word_writer"] == len(dm["samples"]) == 4, "keccak model checks")
    check(dm["rule"].startswith("address = keccak256(ethabi::encode(") and dm["rule"].endswith("[0..20]"), "rule")
    return note


def main():
    try:
        note = verify()
    except VerifyError as e:
        print(f"FAIL: {e}")
        sys.exit(1)
    print(f"PASS: vaults-subaccount-create-94 packet verified (manifest set, regenerated JSON hash and bytes, "
          f"excerpt windows; {note}; pinned facts)")


if __name__ == "__main__":
    main()
