#!/usr/bin/env python3
"""Anchor every behavioural claim about ZSTD_count to a target instruction.

Bounded-claim binding: each row names one claim, the exact virtual address
of the instruction that carries it, and the bytes found there. Every
semantic statement in README.md / records.json has a row here, so a
reviewer can check the claim against the target image itself rather than
against another model.

Regenerated by verify.py and checked byte-for-byte; nothing is executed.
"""
import json
import sys
from pathlib import Path

import capstone

ROOT = Path(__file__).resolve().parents[3]
BINARY = ROOT / "artifacts" / "node" / "115" / "hl-node"
PACKET = (ROOT / "research" / "work-items"
          / "RE-002-node115-zstd-count-6241700-115")

START = 0x6241700
END = 0x62417D3

# (claim, virtual address, note)
CLAIMS = [
    ("limit-8 threshold", 0x6241700,
     "lea computes pInLimit-7; the strict jae makes the effective qword "
     "bound pInLimit-8"),
    ("start pointer saved", 0x6241704,
     "rcx = pIn, the base the final subtraction uses"),
    ("qword tier entry test", 0x6241707,
     "enters the qword loop only while pIn <= pInLimit-8"),
    ("qword load (pMatch)", 0x624170c,
     "loads one qword from pMatch"),
    ("qword load (pIn)", 0x624170f,
     "loads one qword from pIn"),
    ("qword compare", 0x6241712,
     "equal qwords advance both pointers by 8"),
    ("qword mismatch xor", 0x6241790,
     "xor of the two differing qwords"),
    ("qword mismatch tzcnt", 0x6241793,
     "counts trailing zero bits of the xor"),
    ("qword mismatch byte index", 0x6241798,
     "tzcnt >> 3 = equal low-order bytes (little-endian)"),
    ("second qword iteration", 0x6241727,
     "the loop's second qword load, closing the 16-byte step"),
    ("dword tier threshold", 0x6241753,
     "lea computes pInLimit-3; the strict jae makes the effective dword "
     "bound pInLimit-4"),
    ("dword tier test", 0x6241757,
     "enters the dword tier only while pIn <= pInLimit-4"),
    ("dword advance", 0x62417a0,
     "advances by 4 on a dword match"),
    ("word tier threshold", 0x6241762,
     "lea computes pInLimit-1; the strict jae makes the effective word "
     "bound pInLimit-2"),
    ("word tier test", 0x6241766,
     "enters the word tier only while pIn <= pInLimit-2"),
    ("word advance", 0x62417b0,
     "advances by 2 on a word match"),
    ("byte tier test", 0x6241773,
     "enters the byte tier only while pIn < pInLimit"),
    ("byte equality", 0x624177d,
     "sete: the byte tier counts an equal byte"),
    ("byte advance", 0x6241783,
     "advances by 0 or 1 on the byte comparison"),
    ("the cap", 0x6241743,
     "return = current pIn - pIn_start, so the result never exceeds the limit"),
    ("the cap (fallthrough)", 0x6241786,
     "the same subtraction on the 4/2/1-byte fallthrough exit"),
]


def va_to_off(va):
    import re
    import subprocess
    out = subprocess.check_output(["readelf", "-lW", str(BINARY)]).decode()
    for line in out.splitlines():
        p = line.split()
        if p and p[0] == "LOAD":
            v, o, f = int(p[2], 16), int(p[1], 16), int(p[4], 16)
            if v <= va < v + f:
                return o + (va - v)
    raise ValueError(hex(va))


def rows():
    md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_64)
    data = BINARY.read_bytes()
    out = []
    for claim, va, note in CLAIMS:
        assert START <= va < END, (claim, hex(va))
        off = va_to_off(va)
        ins = next(iter(md.disasm(data[off:off + 15], va)))
        raw = data[off:off + ins.size]
        out.append({
            "claim": claim,
            "va": hex(va),
            "size": str(ins.size),
            "bytes": raw.hex(),
            "instruction": f"{ins.mnemonic} {ins.op_str}".strip(),
            "note": note,
        })
    return out


def write(path=None):
    path = path or (PACKET / "semantics.tsv")
    rows_ = rows()
    cols = ("claim", "va", "size", "bytes", "instruction", "note")
    with open(path, "w") as fh:
        fh.write("\t".join(cols) + "\n")
        for r in rows_:
            fh.write("\t".join(r[c] for c in cols) + "\n")
    return len(rows_)


def main():
    n = write()
    print(f"wrote semantics.tsv ({n} claim anchors)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
