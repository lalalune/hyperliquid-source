#!/usr/bin/env python3
"""Anchor every behavioural claim about MaxFileSizeForLevel to a target
instruction.

Bounded-claim binding: each row names one claim, the exact virtual address
of the instruction that carries it, and the bytes found there. Every
semantic statement in README.md / records.json has a row here, so a
reviewer can check the claim against the target image itself rather than
against another model.

Regenerated by verify.py and checked byte-for-byte; nothing is executed.
"""
import re
import subprocess
import sys
from pathlib import Path

import capstone

ROOT = Path(__file__).resolve().parents[3]
BINARY = ROOT / "artifacts" / "node" / "115" / "hl-node"
PACKET = (ROOT / "research" / "work-items"
          / "RE-002-node115-rocksdb-max-file-size-for-level-607f450-115")

START = 0x607F450
END = 0x607F48A

# (claim, virtual address, note)
CLAIMS = [
    ("options pointer kept in rax", 0x607F454,
     "mov %rdi,%rax keeps the options pointer for the one field read"),
    ("level vs base compare", 0x607F457,
     "cmp %ecx,%esi: esi=level against ecx=base; setl records level<base"),
    ("style low byte moved to dil", 0x607F459,
     "mov %edx,%edi puts style in dil, so only its low byte is tested"),
    ("table pointer load", 0x607F45B,
     "mov 0x1e0(%rax),%rdx: the level-indexed table lives at options+0x1e0"),
    ("level<base predicate", 0x607F462,
     "setl %al turns the level/base compare into 0/1"),
    ("style low-byte test", 0x607F465,
     "test %dil,%dil tests ONLY the low byte: style=256 passes as zero"),
    ("style != 0 predicate", 0x607F468,
     "setne %dil turns the low-byte style test into 0/1"),
    ("branch condition combine", 0x607F46C,
     "or %dil,%al: subtract iff (level<base) or (style&0xff)!=0"),
    ("flag test", 0x607F471,
     "cmp $0x1,%r8b: only the low byte of flag is compared"),
    ("default index path", 0x607F477,
     "movslq %esi,%rsi: the plain level index, sign-extended"),
    ("default table read", 0x607F47A,
     "mov (%rdx,%rsi,8),%rax: one 64-bit table entry, step 8, no bound check"),
    ("subtract path", 0x607F480,
     "sub %ecx,%esi: index = level - base, computed in 32 bits"),
    ("subtract index sign-extend", 0x607F482,
     "movslq %esi,%rsi sign-extends the 32-bit difference"),
    ("subtract table read", 0x607F485,
     "the same single 64-bit table read on the subtract path"),
    ("leaf, single return value", 0x607F47E,
     "ret: no stores, no calls, the table value is the whole result"),
]


def va_to_off(va):
    out = subprocess.check_output(["readelf", "-lW", str(BINARY)]).decode()
    for line in out.splitlines():
        p = line.split()
        if p and p[0] == "LOAD":
            v, o, f = int(p[2], 16), int(p[1], 16), int(p[4], 16)
            if v <= va < v + f:
                return o + (va - v)
    raise ValueError(hex(va))


def rows():
    md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_64)
    data = BINARY.read_bytes()
    out = []
    for claim, va, note in CLAIMS:
        assert START <= va < END, (claim, hex(va))
        off = va_to_off(va)
        ins = next(iter(md.disasm(data[off:off + 15], va)))
        raw = data[off:off + ins.size]
        out.append({
            "claim": claim,
            "va": hex(va),
            "size": str(ins.size),
            "bytes": raw.hex(),
            "instruction": f"{ins.mnemonic} {ins.op_str}".strip(),
            "note": note,
        })
    return out


def write(path=None):
    path = path or (PACKET / "semantics.tsv")
    rows_ = rows()
    cols = ("claim", "va", "size", "bytes", "instruction", "note")
    with open(path, "w") as fh:
        fh.write("\t".join(cols) + "\n")
        for r in rows_:
            fh.write("\t".join(r[c] for c in cols) + "\n")
    return len(rows_)


def main():
    n = write()
    print(f"wrote semantics.tsv ({n} claim anchors)")
    return 0


if __name__ == "__main__":
    sys.exit(main())