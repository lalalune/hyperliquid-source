#!/usr/bin/env python3
"""Anchor every behavioural claim about zmemcpy to a target
instruction.

Bounded-claim binding: each row names one claim, the exact virtual address
of the instruction that carries it, and the bytes found there. Every
semantic statement in README.md / records.json has a row here, so a
reviewer can check the claim against the target image itself rather than
against another model.

Regenerated by verify.py and checked byte-for-byte; nothing is executed.
"""
import re
import subprocess
import sys
from pathlib import Path

import capstone

ROOT = Path(__file__).resolve().parents[3]
BINARY = ROOT / "artifacts" / "node" / "115" / "hl-node"
PACKET = (ROOT / "research" / "work-items"
          / "RE-002-node115-libz-zmemcpy-630c430-115")

START = 0x630C430
END = 0x630C558

# (claim, virtual address, note)
CLAIMS = [
    ("function entry", 0x630C430,
     "endbr64: an indirect-branch target, so the window is a routine entry"),
    ("source base for both loops", 0x630C434,
     "mov %rsi,%r8: the source pointer is kept in r8 while rsi is reused as scratch"),
    ("length kept in eax", 0x630C437,
     "mov %edx,%eax: the length survives in eax, which the byte loop then reuses as its index"),
    ("len == 0 test", 0x630C439,
     "test %edx,%edx: a zero length is the first thing ruled out"),
    ("len == 0 returns at once", 0x630C43B,
     "je 0x630c471: nothing is read or written for an empty copy"),
    ("small-length test", 0x630C43D,
     "lea -0x1(%rdx),%edx then cmp $0x6: the test is on len-1, so it is len <= 7"),
    ("small length -> byte loop", 0x630C443,
     "jbe 0x630c455: a short copy goes byte at a time, never through the 16-byte path"),
    ("overlap probe base", 0x630C445,
     "lea 0x1(%rsi),%rsi: the probe compares dest against source+1, not source"),
    ("overlap probe dest", 0x630C449,
     "mov %rdi,%rcx: the destination pointer becomes the minuend"),
    ("unsigned distance", 0x630C44C,
     "sub %rsi,%rcx computes dest-(source+1) as an UNSIGNED difference, so dest <= source wraps to a huge value"),
    ("overlap bound", 0x630C44F,
     "cmp $0xe,%rcx: the guard fires when dest-(source+1) <= 14"),
    ("overlap -> byte loop", 0x630C453,
     "ja 0x630c478: only diff > 14 takes the chunk path, i.e. the byte loop is kept for 1 <= dest-source <= 15"),
    ("byte loop load", 0x630C460,
     "movzbl (%r8,%rax,1),%ecx: one byte read from the source, observing any earlier store"),
    ("byte loop store", 0x630C465,
     "mov %cl,(%rdi,%rax,1): one byte written to the destination, so an overlap repeats forward"),
    ("byte loop bound", 0x630C46C,
     "cmp %rax,%rdx with jne: the loop runs exactly len times"),
    ("tail-only length test", 0x630C478,
     "cmp $0xe,%edx then jbe 0x630c548: len <= 15 skips the chunk loop and goes straight to byte-at-a-time copying"),
    ("chunk load snapshots 16 bytes", 0x630C490,
     "movdqu (%r8,%rdx,1),%xmm0: an unaligned 16-byte load, so the chunk is snapshotted before any store"),
    ("chunk store writes 16 bytes", 0x630C496,
     "movups %xmm0,(%rdi,%rdx,1): the snapshot is stored, which is why the chunk path may NOT be used on overlap"),
    ("return", 0x630C471,
     "ret: the routine has no return value - it is void, and every caller's rax use after the call is its own"),
]


def va_to_off(va):
    out = subprocess.check_output(["readelf", "-lW", str(BINARY)]).decode()
    for line in out.splitlines():
        p = line.split()
        if p and p[0] == "LOAD":
            v, o, f = int(p[2], 16), int(p[1], 16), int(p[4], 16)
            if v <= va < v + f:
                return o + (va - v)
    raise ValueError(hex(va))


def rows():
    md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_64)
    data = BINARY.read_bytes()
    out = []
    for claim, va, note in CLAIMS:
        assert START <= va < END, (claim, hex(va))
        off = va_to_off(va)
        ins = next(iter(md.disasm(data[off:off + 15], va)))
        raw = data[off:off + ins.size]
        out.append({
            "claim": claim,
            "va": hex(va),
            "size": str(ins.size),
            "bytes": raw.hex(),
            "instruction": f"{ins.mnemonic} {ins.op_str}".strip(),
            "note": note,
        })
    return out


def write(path=None):
    path = path or (PACKET / "semantics.tsv")
    rows_ = rows()
    cols = ("claim", "va", "size", "bytes", "instruction", "note")
    with open(path, "w") as fh:
        fh.write("\t".join(cols) + "\n")
        for r in rows_:
            fh.write("\t".join(r[c] for c in cols) + "\n")
    return len(rows_)


def main():
    n = write()
    print(f"wrote semantics.tsv ({n} claim anchors)")
    return 0


if __name__ == "__main__":
    sys.exit(main())