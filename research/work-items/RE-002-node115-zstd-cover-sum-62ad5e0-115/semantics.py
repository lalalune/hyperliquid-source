#!/usr/bin/env python3
"""Anchor every behavioural claim about COVER_sum to a target
instruction.

Bounded-claim binding: each row names one claim, the exact virtual address
of the instruction that carries it, and the bytes found there. Every
semantic statement in README.md / records.json has a row here, so a
reviewer can check the claim against the target image itself rather than
against another model.

Regenerated by verify.py and checked byte-for-byte; nothing is executed.
"""
import re
import subprocess
import sys
from pathlib import Path

import capstone

ROOT = Path(__file__).resolve().parents[3]
BINARY = ROOT / "artifacts" / "node" / "115" / "hl-node"
PACKET = (ROOT / "research" / "work-items"
          / "RE-002-node115-zstd-cover-sum-62ad5e0-115")

START = 0x62AD5E0
END = 0x62AD641

# (claim, virtual address, note)
CLAIMS = [
    ("function entry", 0x62AD5E0,
     "endbr64: an indirect-branch target, so the window is a routine entry"),
    ("n == 0 test", 0x62AD5E4,
     "test %esi,%esi: the count is tested before anything is read"),
    ("n == 0 early return", 0x62AD5E6,
     "je 0x62ad638: zero elements jumps straight to the zeroed result"),
    ("n == 1 test", 0x62AD5E8,
     "cmp $0x1,%esi: the single-element case gets its own branch"),
    ("n == 1 enters the tail add", 0x62AD5EB,
     "je 0x62ad63b: n == 1 jumps into the SHARED scalar add, not a copy of it"),
    ("iteration count n >> 1", 0x62AD5F6,
     "shr $1,%edx: the vector loop runs n>>1 times, two elements per pass"),
    ("vector end pointer", 0x62AD5FC,
     "add %rdi,%rdx after shl $0x4: end = splits + 16*(n>>1)"),
    ("two splits loaded at once", 0x62AD600,
     "movdqu (%rax),%xmm2: an unaligned 16-byte load of two size_t elements"),
    ("lane-wise 64-bit add", 0x62AD608,
     "paddq %xmm2,%xmm0: 64-bit lanes, so no carry crosses into the next lane"),
    ("loop bound", 0x62AD60C,
     "cmp %rax,%rdx with jne: the loop ends when the pointer reaches the end"),
    ("horizontal fold", 0x62AD615,
     "psrldq $0x8,%xmm1 places the high lane low so paddq can add it in"),
    ("fold adds the high lane", 0x62AD61A,
     "paddq %xmm1,%xmm0: the second of the two 64-bit lanes joins the sum"),
    ("low lane is the result", 0x62AD61E,
     "movq %xmm0,%rax: only the low lane is kept, so the sum is modulo 2**64"),
    ("odd element test", 0x62AD623,
     "test $0x1,%sil with je: an even count skips the scalar tail"),
    ("tail index is n & ~1", 0x62AD629,
     "and $0xfffffffe,%esi: the tail element is the LAST index (n-1) of an odd n"),
    ("single scalar add from memory", 0x62AD62C,
     "add (%rdi,%rsi,8),%rax: the only scalar add, shared by n == 1 and the tail"),
    ("return", 0x62AD630,
     "ret: no stores and no calls; the accumulated value is the whole result"),
    ("n == 1 zeroes the index", 0x62AD63B,
     "xor %esi,%esi then xor %eax,%eax and jmp: n == 1 sums exactly splits[0]"),
    ("n == 0 zeroes the result", 0x62AD638,
     "xor %eax,%eax: the empty slice returns 0 without touching splits"),
]


def va_to_off(va):
    out = subprocess.check_output(["readelf", "-lW", str(BINARY)]).decode()
    for line in out.splitlines():
        p = line.split()
        if p and p[0] == "LOAD":
            v, o, f = int(p[2], 16), int(p[1], 16), int(p[4], 16)
            if v <= va < v + f:
                return o + (va - v)
    raise ValueError(hex(va))


def rows():
    md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_64)
    data = BINARY.read_bytes()
    out = []
    for claim, va, note in CLAIMS:
        assert START <= va < END, (claim, hex(va))
        off = va_to_off(va)
        ins = next(iter(md.disasm(data[off:off + 15], va)))
        raw = data[off:off + ins.size]
        out.append({
            "claim": claim,
            "va": hex(va),
            "size": str(ins.size),
            "bytes": raw.hex(),
            "instruction": f"{ins.mnemonic} {ins.op_str}".strip(),
            "note": note,
        })
    return out


def write(path=None):
    path = path or (PACKET / "semantics.tsv")
    rows_ = rows()
    cols = ("claim", "va", "size", "bytes", "instruction", "note")
    with open(path, "w") as fh:
        fh.write("\t".join(cols) + "\n")
        for r in rows_:
            fh.write("\t".join(r[c] for c in cols) + "\n")
    return len(rows_)


def main():
    n = write()
    print(f"wrote semantics.tsv ({n} claim anchors)")
    return 0


if __name__ == "__main__":
    sys.exit(main())