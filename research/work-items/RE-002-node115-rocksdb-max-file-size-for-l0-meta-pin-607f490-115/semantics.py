#!/usr/bin/env python3
"""Anchor every behavioural claim about MaxFileSizeForL0MetaPin to a target
instruction.

Bounded-claim binding: each row names one claim, the exact virtual address
of the instruction that carries it, and the bytes found there. Every
semantic statement in README.md / records.json has a row here, so a
reviewer can check the claim against the target image itself rather than
against another model.

Regenerated by verify.py and checked byte-for-byte; nothing is executed.
"""
import re
import subprocess
import sys
from pathlib import Path

import capstone

ROOT = Path(__file__).resolve().parents[3]
BINARY = ROOT / "artifacts" / "node" / "115" / "hl-node"
PACKET = (ROOT / "research" / "work-items"
          / "RE-002-node115-rocksdb-max-file-size-for-l0-meta-pin-607f490-115")

START = 0x607F490
END = 0x607F4BB

# (claim, virtual address, note)
CLAIMS = [
    ("function entry", 0x607F490,
     "endbr64: an indirect-branch target, so the window is a routine entry"),
    ("single field read from the options pointer", 0x607F494,
     "mov (%rdi),%rdx: the only memory this routine reads is *rdi"),
    ("sentinel result preloaded", 0x607F497,
     "mov $0xffffffffffffffff,%rax seeds the all-ones return value"),
    ("overflow threshold constant", 0x607F49E,
     "movabs $0xaaaaaaaaaaaaaaab,%rcx: the largest input whose 3*(value>>1)"
     " still fits; value == the threshold computes exactly and yields all ones"),
    ("threshold against the input", 0x607F4A8,
     "cmp %rdx,%rcx compares the threshold with the loaded field"),
    ("unsigned guard branch", 0x607F4AB,
     "jb: UNSIGNED below, so the sentinel is returned iff threshold < value"),
    ("accepted path keeps the value", 0x607F4AD,
     "mov %rdx,%rax is the first instruction of the accepted path"),
    ("low bit cleared", 0x607F4B0,
     "and $0xfffffffffffffffe,%rdx turns the value into 2*(value>>1)"),
    ("halving shift", 0x607F4B4,
     "shr $1,%rax is value>>1, so an odd input truncates BEFORE the x3"),
    ("sum is three halves", 0x607F4B7,
     "add %rdx,%rax: (value>>1) + 2*(value>>1) = 3*(value>>1)"),
    ("leaf return", 0x607F4BA,
     "ret: no stores and no calls, the value is the whole result"),
]


def va_to_off(va):
    out = subprocess.check_output(["readelf", "-lW", str(BINARY)]).decode()
    for line in out.splitlines():
        p = line.split()
        if p and p[0] == "LOAD":
            v, o, f = int(p[2], 16), int(p[1], 16), int(p[4], 16)
            if v <= va < v + f:
                return o + (va - v)
    raise ValueError(hex(va))


def rows():
    md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_64)
    data = BINARY.read_bytes()
    out = []
    for claim, va, note in CLAIMS:
        assert START <= va < END, (claim, hex(va))
        off = va_to_off(va)
        ins = next(iter(md.disasm(data[off:off + 15], va)))
        raw = data[off:off + ins.size]
        out.append({
            "claim": claim,
            "va": hex(va),
            "size": str(ins.size),
            "bytes": raw.hex(),
            "instruction": f"{ins.mnemonic} {ins.op_str}".strip(),
            "note": note,
        })
    return out


def write(path=None):
    path = path or (PACKET / "semantics.tsv")
    rows_ = rows()
    cols = ("claim", "va", "size", "bytes", "instruction", "note")
    with open(path, "w") as fh:
        fh.write("\t".join(cols) + "\n")
        for r in rows_:
            fh.write("\t".join(r[c] for c in cols) + "\n")
    return len(rows_)


def main():
    n = write()
    print(f"wrote semantics.tsv ({n} claim anchors)")
    return 0


if __name__ == "__main__":
    sys.exit(main())