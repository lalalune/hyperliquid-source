    ("the continuation test is the byte's bit 7", 0x61BD524,
     "test %dil,%dil is an 8-bit AND; SF therefore reflects bit 7 of the byte"),
    ("continuation branch on the sign flag", 0x61BD527,
     "js 0x61bd508 -> bit 7 set means another byte follows"),
    ("final byte shift", 0x61BD529,
     "shl %cl,%edi places the final byte at the accumulated shift"),
    ("final byte merge", 0x61BD52B,
     "or %r8d,%edi merges the low bits already accumulated"),
    ("the single 32-bit store", 0x61BD52E,
     "mov %edi,(%rdx) writes the value through the uint32_t* - 4 bytes, 32-bit wide; nothing else is written"),
