#!/usr/bin/env python3
"""Anchor every behavioural claim about BIT_reloadDStream_internal to a target
instruction.

Bounded-claim binding: each row names one claim, the exact virtual address
of the instruction that carries it, and the bytes found there. Every
semantic statement in README.md / records.json has a row here, so a
reviewer can check the claim against the target image itself rather than
against another model.

Regenerated by verify.py and checked byte-for-byte; nothing is executed.
"""
import re
import subprocess
import sys
from pathlib import Path

import capstone

ROOT = Path(__file__).resolve().parents[3]
BINARY = ROOT / "artifacts" / "node" / "115" / "hl-node"
PACKET = (ROOT / "research" / "work-items"
          / "RE-002-node115-zstd-bit-reload-dstream-internal-628f710-115")

START = 0x628F710
END = 0x628F732

# (claim, virtual address, note)
CLAIMS = [
    ("the body opens by loading bitsConsumed", 0x628F710,
     "mov 0x8(%rdi),%edx: the window starts with a 32-bit load of the consumed-bit count at +0x08, and there is NO endbr64 - this body is never an indirect-branch target and does nothing else first"),
    ("the stream pointer is read", 0x628F713,
     "mov 0x10(%rdi),%rax: the byte pointer lives at +0x10"),
    ("the copy zero-extends into a 64-bit register", 0x628F717,
     "mov %edx,%ecx clears the upper 32 bits, so the rewind is unsigned and cannot go negative"),
    ("the sub-byte remainder is isolated", 0x628F719,
     "and $0x7,%edx leaves bitPos = bitsConsumed & 7"),
    ("the whole bytes are isolated", 0x628F71C,
     "shr $0x3,%ecx computes bitsConsumed >> 3 - the number of whole bytes to rewind"),
    ("the remainder is written back as the new bitsConsumed", 0x628F71F,
     "mov %edx,0x8(%rdi): after the call bitsConsumed is always in [0,7]"),
    ("the pointer moves BACKWARD", 0x628F722,
     "sub %rcx,%rax: the rewind re-reads bytes already delivered instead of advancing"),
    ("the rewound pointer is stored", 0x628F725,
     "mov %rax,0x10(%rdi) commits the rewound pointer before the load"),
    ("one unconditional 8-byte little-endian container load", 0x628F729,
     "mov (%rax),%rax loads exactly 8 bytes from the rewound pointer - MEM_readLEST, with no bounds check of any kind"),
    ("the container is REPLACED, not merged", 0x628F72C,
     "mov %rax,(%rdi) stores the newly loaded word over the whole container: no shift, no OR with the previous bits"),
    ("the return value is the constant 0", 0x628F72F,
     "xor %eax,%eax on the only path: the value carries no information (no comparison exists in the body)"),
    ("the only exit", 0x628F731,
     "a single ret: the 12-instruction body has no conditional branch"),
]


def va_to_off(va):
    out = subprocess.check_output(["readelf", "-lW", str(BINARY)]).decode()
    for line in out.splitlines():
        p = line.split()
        if p and p[0] == "LOAD":
            v, o, f = int(p[2], 16), int(p[1], 16), int(p[4], 16)
            if v <= va < v + f:
                return o + (va - v)
    raise ValueError(hex(va))


def rows():
    md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_64)
    data = BINARY.read_bytes()
    out = []
    for claim, va, note in CLAIMS:
        assert START <= va < END, (claim, hex(va))
        off = va_to_off(va)
        ins = next(iter(md.disasm(data[off:off + 15], va)))
        raw = data[off:off + ins.size]
        out.append({
            "claim": claim,
            "va": hex(va),
            "size": str(ins.size),
            "bytes": raw.hex(),
            "instruction": f"{ins.mnemonic} {ins.op_str}".strip(),
            "note": note,
        })
    return out


def write(path=None):
    path = path or (PACKET / "semantics.tsv")
    rows_ = rows()
    cols = ("claim", "va", "size", "bytes", "instruction", "note")
    with open(path, "w") as fh:
        fh.write("\t".join(cols) + "\n")
        for r in rows_:
            fh.write("\t".join(r[c] for c in cols) + "\n")
    return len(rows_)


def main():
    n = write()
    print(f"wrote semantics.tsv ({n} claim anchors)")
    return 0


if __name__ == "__main__":
    sys.exit(main())