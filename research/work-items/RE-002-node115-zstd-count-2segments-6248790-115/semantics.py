def va_to_off(va):
    out = subprocess.check_output(["readelf", "-lW", str(BINARY)]).decode()
    for line in out.splitlines():
        p = line.split()
        if p and p[0] == "LOAD":
            v, o, f = int(p[2], 16), int(p[1], 16), int(p[4], 16)
            if v <= va < v + f:
                return o + (va - v)
    raise ValueError(hex(va))


def rows():
    md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_64)
    data = BINARY.read_bytes()
    out = []
    for claim, va, note in CLAIMS:
        assert START <= va < END, (claim, hex(va))
        off = va_to_off(va)
        ins = next(iter(md.disasm(data[off:off + 15], va)))
        raw = data[off:off + ins.size]
        out.append({
            "claim": claim,
            "va": hex(va),
            "size": str(ins.size),
            "bytes": raw.hex(),
            "instruction": f"{ins.mnemonic} {ins.op_str}".strip(),
            "note": note,
        })
    return out


def write(path=None):
    path = path or (PACKET / "semantics.tsv")
    rows_ = rows()
    cols = ("claim", "va", "size", "bytes", "instruction", "note")
    with open(path, "w") as fh:
        fh.write("\t".join(cols) + "\n")
        for r in rows_:
            fh.write("\t".join(r[c] for c in cols) + "\n")
    return len(rows_)


def main():
    n = write()
    print(f"wrote semantics.tsv ({n} claim anchors)")
    return 0


if __name__ == "__main__":
    sys.exit(main())