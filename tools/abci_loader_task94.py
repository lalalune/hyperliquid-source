def check_extent(image, start, record, index_row):
    require(start in OWNERS, 'unexpected FDE owner')
    end, wanted_hash = OWNERS[start]
    require(record['start'] == start and record['end'] == end, 'FDE extent mismatch')
    require(index_row['start'] == start and index_row['fde'] == record['fde'],
            'FDE/header entry mismatch')
    body = image.read(start, end - start, executable=True)
    actual = hashlib.sha256(body).hexdigest()
