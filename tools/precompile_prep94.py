def sha(data):
    return hashlib.sha256(data).hexdigest()


class Image:
    def __init__(self, data):
        require(sha(data) == TARGET_SHA256, 'node94 digest mismatch')
        self.data = data
        self.sections = sections(data)
        _, self.index = unwind_index(data)
        _, records = eh_frame_records(data, self.sections)
        self.fdes = {}
        for record in records:
            self.fdes.setdefault(record['start'], []).append(record)
        self.validate_functions()
        self.relocations = {}
        rel = self.named_section('.rela.dyn')
        require(rel['type'] == 4 and rel['size'] % 24 == 0, 'invalid RELA section')
        for pos in range(rel['offset'], rel['offset'] + rel['size'], 24):
            location, info, addend = struct.unpack_from('<QQq', data, pos)
            require(location not in self.relocations, 'duplicate RELA location')
            self.relocations[location] = (info, addend, pos)

    def validate_functions(self):
        index_by_start = {entry['start']: entry for entry in self.index}
        require(len(index_by_start) == len(self.index), 'duplicate unwind starts')
        for start, (end, digest, _) in FUNCTIONS.items():
            entries = self.fdes.get(start, [])
            require(len(entries) == 1, f'missing or duplicate FDE at {start:#x}')
            record = entries[0]
            require(record['end'] == end, f'changed FDE extent at {start:#x}')
            require(start in index_by_start and index_by_start[start]['fde'] == record['fde'],
                    f'FDE not bound by unwind index at {start:#x}')
            require(sha(self.read(start, end-start)) == digest, f'changed function body at {start:#x}')
            require(self.section_at(start, end-start)['flags'] & 4, 'FDE not in executable section')

    def named_section(self, name):
        matches = [s for s in self.sections if s['name'] == name and s['type'] != 8]
        require(len(matches) == 1, f'missing, duplicate or NOBITS section {name}')
        return matches[0]

    def section_at(self, va, size):
        require(isinstance(va, int) and isinstance(size, int) and va >= 0 and size > 0,
                'invalid address or size')
        found = [s for s in self.sections if s['type'] != 8 and s['flags'] & 2
                 and s['address'] <= va and va + size <= s['address'] + s['size']]
        require(len(found) == 1, f'no unique file-backed allocated range at {va:#x}')
        return found[0]

    def offset(self, va, size):
        section = self.section_at(va, size)
        return section['offset'] + va - section['address']

    def read(self, va, size):
        pos = self.offset(va, size)
        return self.data[pos:pos+size]

    def relative(self, location, expected=None):
        record = self.relocations.get(location)
        require(record is not None, f'missing relocation at {location:#x}')
        info, addend, offset = record
        require(info == 8, f'not symbol-free R_X86_64_RELATIVE at {location:#x}')
        if expected is not None:
            require(addend == expected, f'wrong relocation addend at {location:#x}')
        return info, addend, offset

    def record_bytes(self, va):
        header = self.read(va, 4)
        length = struct.unpack('<I', header)[0]
        require(0 < length < 0xffffffff, 'unsupported or empty frame record')
        return self.read(va, 4 + length)


def verify_window(img, owner, start, end, expected):
    require(owner in FUNCTIONS and owner <= start < end <= FUNCTIONS[owner][0], 'window outside owner FDE')
    raw = img.read(start, end-start)
    require(raw.hex() == expected, f'window mismatch at {start:#x}')
    return raw


def decode_transfer(site, raw):
    """Decode only the pinned direct relative transfer forms in BRANCHES."""
    require(len(raw) >= 2, 'truncated direct transfer')
    if raw[0] in (0xe8, 0xe9):
        require(len(raw) == 5, 'invalid rel32 length')
        kind = 'call' if raw[0] == 0xe8 else 'jump'
        delta = struct.unpack_from('<i', raw, 1)[0]
    elif raw[0] == 0xeb or 0x70 <= raw[0] <= 0x7f:
        require(len(raw) == 2, 'invalid rel8 length')
        kind = 'jump' if raw[0] == 0xeb else 'conditional'
        delta = struct.unpack_from('<b', raw, 1)[0]
    elif raw[0] == 0x0f and 0x80 <= raw[1] <= 0x8f:
        require(len(raw) == 6, 'invalid conditional rel32 length')
        kind = 'conditional'
        delta = struct.unpack_from('<i', raw, 2)[0]
    else:
        raise ValueError('unsupported direct transfer opcode')
    return kind, site + len(raw) + delta


def indirect_target(img, site, slot, target):
    raw = img.read(site, 7 if site == 0x4ea2ecd else 6)
    if raw[:2] == b'\xff\x15' and len(raw) == 6:
        disp = struct.unpack_from('<i', raw, 2)[0]
    elif raw[:3] == b'\x48\x8b\x05' and len(raw) == 7:
        disp = struct.unpack_from('<i', raw, 3)[0]
    else:
        raise ValueError(f'unsupported indirect shape at {site:#x}')
    require(site + len(raw) + disp == slot, 'RIP displacement mismatch')
    info, actual, off = img.relative(slot, target)
    return raw, info, actual, off


def exception_table(img, fde):
    """Read only the observed LSDA call-site encoding; action chains stay opaque."""
    if fde['lsda'] is None:
        return [], None
    va = fde['lsda']
    section = img.named_section('.gcc_except_table')
    off = img.offset(va, 1)
    require(section['offset'] <= off < section['offset'] + section['size'], 'LSDA outside exception section')
    data = img.data
    end = section['offset'] + section['size']
    pos = off
    require(data[pos] == 0xff, 'unsupported landing base')
    pos += 1
    require(pos < end, 'truncated LSDA type encoding')
    type_encoding = data[pos]
    pos += 1
    type_base = None
    if type_encoding != 0xff:
        require(type_encoding == 0x9b, 'unsupported type encoding')
        delta, pos = uleb(data, pos, end)
        type_base = pos + delta
        require(type_base <= end, 'type table outside section')
    require(pos < end and data[pos] == 1, 'unsupported call-site encoding')
    pos += 1
    length, pos = uleb(data, pos, end)
    limit = pos + length
    require(limit <= end and (type_base is None or limit <= type_base), 'invalid call-site extent')
    rows, previous = [], 0
    while pos < limit:
        record = pos
        start, pos = uleb(data, pos, limit)
        size, pos = uleb(data, pos, limit)
        landing, pos = uleb(data, pos, limit)
        action, pos = uleb(data, pos, limit)
        require(start >= previous and fde['start'] + start + size <= fde['end'], 'invalid exception interval')
        require(not landing or fde['start'] + landing < fde['end'], 'invalid landing pad')
        previous = start + size
        rows.append((hx(fde['start']), hx(va), hx(record), hx(fde['start']+start),
                     size, hx(fde['start']+start+size),
                     hx(fde['start']+landing) if landing else '', action, data[record:pos].hex()))
    raw_end = type_base if type_base is not None else limit
    header = {'owner': hx(fde['start']), 'lsda_va': hx(va), 'file_offset': hx(off),
              'type_encoding': hx(type_encoding), 'table_end_file_offset': hx(limit),
              'raw_prefix': data[off:raw_end].hex(),
              'limit': 'Call-site records only; action chains and catch types are not interpreted.'}
    return rows, header


def dynamic_symbol(img, location):
    record = img.relocations.get(location)
    require(record is not None, 'missing symbol relocation')
    info, addend, pos = record
    kind, index = info & 0xffffffff, info >> 32
    require(kind == 6 and index > 0, 'not a GLOB_DAT symbol relocation')
    symbols = img.named_section('.dynsym')
    strings = img.named_section('.dynstr')
    require(symbols['type'] == 11 and symbols['size'] % 24 == 0, 'invalid dynamic symbol table')
    require(index < symbols['size'] // 24, 'dynamic symbol index outside table')
    symoff = symbols['offset'] + index*24
    nameoff, st_info, other, shndx, value, size = struct.unpack_from('<IBBHQQ', img.data, symoff)
    require(nameoff < strings['size'], 'dynamic symbol name outside table')
    beg = strings['offset'] + nameoff
    stop = img.data.find(b'\0', beg, strings['offset'] + strings['size'])
    require(stop >= 0, 'unterminated symbol name')
    name = img.data[beg:stop].decode('ascii')
    return {'slot_va': hx(location), 'relocation_file_offset': hx(pos), 'relocation_type': kind,
            'symbol_index': index, 'symbol_name': name, 'symbol_info': st_info,
            'symbol_shndx': shndx, 'symbol_value': hx(value), 'symbol_size': size, 'addend': addend}


